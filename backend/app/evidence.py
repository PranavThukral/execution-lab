"""Generate a reproducible, credential-free recruiting evidence pack."""

from __future__ import annotations

import argparse
import csv
import json
import platform
import statistics
from datetime import date
from pathlib import Path
from time import perf_counter

from .domain import ENGINE_VERSION, demo_bars, run_simulation

CASES = {
    "baseline": {"quantity": 50000},
    "liquidity-squeeze": {"quantity": 200000, "liquidity_multiplier": 0.2},
    "sell-timing": {"quantity": 50000, "side": "sell", "price_path_multiplier": 3},
}


def build_pack(output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    bars = demo_bars()
    results = {}
    for name, parameters in CASES.items():
        result = run_simulation(bars, date(2025, 6, 9), 30, 90, **parameters)
        results[name] = result
        (output_dir / f"{name}.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
        for strategy in result["strategies"]:
            headers = list(strategy["fills"][0]) if strategy["fills"] else ["strategy", "shares"]
            with (output_dir / f"{name}-{strategy['strategy']}.csv").open(
                "w", encoding="utf-8", newline=""
            ) as handle:
                writer = csv.DictWriter(handle, fieldnames=headers)
                writer.writeheader()
                writer.writerows(strategy["fills"])
    timings = []
    for _ in range(100):
        started = perf_counter()
        run_simulation(bars, date(2025, 6, 9), 30, 90, 50000)
        timings.append((perf_counter() - started) * 1000)
    benchmark = {
        "engine_version": ENGINE_VERSION,
        "python": platform.python_version(),
        "platform": platform.platform(),
        "bars": len(bars),
        "window_minutes": 60,
        "iterations": 100,
        "p50_ms": statistics.median(timings),
        "p95_ms": sorted(timings)[94],
        "scope": (
            "Warm engine: profiles/hash/metrics included. "
            "Startup, network, serialization and UI excluded."
        ),
    }
    (output_dir / "benchmark.json").write_text(json.dumps(benchmark, indent=2), encoding="utf-8")
    lines = [
        "# Execution Lab: three reproducible execution decisions",
        "",
        "Generated by `uv run python -m app.evidence --output-dir ../evidence`.",
        "Synthetic SIM_DEMO: June 9 2025, 10:00–11:00 America/New_York, USD.",
        "Engineering examples; no empirical market performance or calibrated costs are claimed.",
        "",
        "| Case | Schedule | Filled shares | Residual shares | Shortfall USD | Shortfall bps |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for name, result in results.items():
        for strategy in result["strategies"]:
            lines.append(
                f"| {name} | {strategy['strategy']} | {strategy['filled_shares']:,} | "
                f"{strategy['unfilled_shares']:,} | {strategy['implementation_shortfall']:,.2f} | "
                f"{strategy['implementation_shortfall_bps']:.2f} |"
            )
    lines.extend(
        [
            "",
            "## What to explain in an interview",
            "",
            (
                "Baseline: urgency reduces exposure to this rising buy path. "
                "Spread and impact remain modeled. Inspect attribution before choosing a schedule."
            ),
            "",
            (
                "Liquidity squeeze: replay capacity bounds completion under this fill model. "
                "Residual shares matter even if filled-only slippage looks favorable."
            ),
            "",
            (
                "Sell timing: reversing side changes signed timing/opportunity costs. "
                "A buy-path conclusion does not automatically transfer to selling."
            ),
            "",
            (
                "The prior-session estimate cannot see evaluation volume; realized capacity can. "
                "A schedule can fail despite sufficient aggregate capacity because timing "
                "constrains access to liquidity."
            ),
            "",
            f"Engine {ENGINE_VERSION}; "
            f"dataset SHA-256 `{results['baseline']['dataset']['content_sha256']}`.",
            "",
            f"Warm engine, 100 iterations: p50 {benchmark['p50_ms']:.2f} ms, "
            f"p95 {benchmark['p95_ms']:.2f} ms. See benchmark.json for scope and environment.",
            "",
            (
                "JSON retains request, assumptions, prior dates, warnings, diagnostics and fills. "
                "CSV supports independent reconciliation."
            ),
        ]
    )
    (output_dir / "CASE_STUDY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(benchmark))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path("../evidence"))
    build_pack(parser.parse_args().output_dir)


if __name__ == "__main__":
    main()
